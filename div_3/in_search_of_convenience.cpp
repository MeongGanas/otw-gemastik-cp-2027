void solve() {
    int x, y, r; cin >> x >> y >> r;

    int a_val = -1, b_val = -1;

    for (int a = 0; a <= r; a++) {
        int rem = r * r - a * a;
        int b = round(sqrt(rem));
        
        if (b * b == rem) {
            a_val = a;
            b_val = b;
            break;
        }
    }

    x = x + a_val;
    y = y + b_val;

    cout << x << " " << y << endl;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }

    return 0;
}