void solve() {
    string s;
    cin >> s;

    int ans = 1;

    if (s.find("010") != string::npos || s.find("101") != string::npos) {
        ans++;
    }

    if (s.find("000") != string::npos || s.find("111") != string::npos) {
        ans++;
    }

    cout << ans << '\n';
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }

    return 0;
}

